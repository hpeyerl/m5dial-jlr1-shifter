/**
 * logo_lines.h
 *
 * Vector line data for logo rendering on M5Dial (GC9A01, 240x240).
 *
 * Coordinates are normalized to the range [-1.0, 1.0] centered at the
 * origin. To draw at runtime:
 *
 *   1. Read accelerometer axes (ax, ay).
 *   2. Compute rotation angle:  float angle = atan2f(ax, ay);
 *   3. For each line, rotate both endpoints by -angle, then scale to
 *      screen pixels and call your drawLine() function.
 *
 * Rotation helper (maps normalized coords -> screen pixels):
 *
 *   void transformPoint(float nx, float ny, float angle,
 *                       int16_t *sx, int16_t *sy) {
 *       float cosA = cosf(angle), sinA = sinf(angle);
 *       float rx = nx * cosA - ny * sinA;
 *       float ry = nx * sinA + ny * cosA;
 *       *sx = (int16_t)(LOGO_RADIUS * rx) + LOGO_CENTER_X;
 *       *sy = (int16_t)(LOGO_RADIUS * ry) + LOGO_CENTER_Y;  // note: Y flipped below
 *   }
 *
 * Suggested constants for M5Dial 240x240 display:
 *   #define LOGO_CENTER_X  120
 *   #define LOGO_CENTER_Y  120
 *   #define LOGO_RADIUS    110   // leaves a small margin
 *
 * Y-axis note: DXF uses Y-up; screen uses Y-down.
 * Negate ny before transforming, or negate sinA terms - handled here by
 * storing y values already negated (Y-flipped) in the table.
 *
 * Total line segments: 147
 * Source: logo_wide_symmetric.dxf
 */

